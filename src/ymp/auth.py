"""Server users: the logins phone apps use, and how each request is checked.

Subsonic's token login sends md5(password + salt), so the server has to know the
password itself; it cannot just keep a hash. So:
  - passwords are random, generated by ymp (never a password used anywhere else),
  - they are stored encrypted with DPAPI in the "server_users" credential store,
  - the API is only reachable on the home network / Tailscale (see settings.server_bind).
Phase 5 adds per-device tokens for our own Android app on top of this.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
import threading
import time
from collections import defaultdict, deque
from dataclasses import dataclass

from . import credstore
from .paths import safe_name

STORE = "server_users"
MAX_FAILURES = 10          # failed logins per client address ...
FAILURE_WINDOW_S = 15 * 60  # ... within this window lock that address out for the window


@dataclass
class ServerUser:
    name: str
    profile: str
    password: str


def new_password() -> str:
    # ~95 bits; letters and digits only so it's easy to type into a phone.
    alphabet = "abcdefghijkmnpqrstuvwxyzACDEFGHJKLMNPQRTUVWXYZ2345679"
    return "-".join("".join(secrets.choice(alphabet) for _ in range(6)) for _ in range(3))


def _check_name(name: str) -> str:
    if not name or safe_name(name) != name or len(name) > 40:
        raise ValueError(f"'{name}' isn't a usable user name (letters, digits, - and _ only)")
    return name


def add_user(name: str, profile: str, password: str | None = None) -> ServerUser:
    _check_name(name)
    if credstore.load(name, STORE) is not None:
        raise ValueError(f"Server user '{name}' already exists")
    return set_password(name, profile, password)


def set_password(name: str, profile: str | None = None, password: str | None = None) -> ServerUser:
    existing = credstore.load(_check_name(name), STORE)
    profile = profile or (existing or {}).get("profile")
    if not profile:
        raise ValueError(f"No server user '{name}'")
    user = ServerUser(name, profile, password or new_password())
    credstore.save(name, {"profile": user.profile, "password": user.password}, STORE)
    return user


def get_user(name: str) -> ServerUser | None:
    try:
        data = credstore.load(safe_name(name), STORE) if name else None
    except credstore.CredentialError:
        return None
    if not data or safe_name(name) != name:
        return None
    return ServerUser(name, data["profile"], data["password"])


def list_users() -> list[ServerUser]:
    return [u for u in map(get_user, credstore.list_profiles(STORE)) if u]


def remove_user(name: str) -> bool:
    return credstore.delete(_check_name(name), STORE)


def check_subsonic(user: ServerUser, password: str | None, token: str | None,
                   salt: str | None) -> bool:
    """Subsonic login: either t=md5(password+s)&s=salt, or p=password / p=enc:HEX."""
    if token and salt:
        expected = hashlib.md5((user.password + salt).encode("utf-8")).hexdigest()
        return hmac.compare_digest(expected, token.lower())
    if password:
        if password.startswith("enc:"):
            try:
                password = bytes.fromhex(password[4:]).decode("utf-8")
            except ValueError:
                return False
        return hmac.compare_digest(password.encode("utf-8"), user.password.encode("utf-8"))
    return False


class Lockout:
    """Too many failed logins from one address -> refuse it for a while."""

    def __init__(self, max_failures: int = MAX_FAILURES, window_s: float = FAILURE_WINDOW_S):
        self.max_failures, self.window_s = max_failures, window_s
        self._failures: dict[str, deque[float]] = defaultdict(deque)
        self._lock = threading.Lock()

    def _trim(self, client: str, now: float) -> deque[float]:
        q = self._failures[client]
        while q and q[0] < now - self.window_s:
            q.popleft()
        return q

    def is_locked(self, client: str) -> bool:
        with self._lock:
            return len(self._trim(client, time.monotonic())) >= self.max_failures

    def failed(self, client: str) -> None:
        with self._lock:
            now = time.monotonic()
            self._trim(client, now).append(now)

    def succeeded(self, client: str) -> None:
        with self._lock:
            self._failures.pop(client, None)
