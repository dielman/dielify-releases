"""Server users: the logins phone apps use, and how each request is checked.

Subsonic's token login sends md5(password + salt), so the server has to know the
password itself; it cannot just keep a hash. So:
  - passwords are random, generated by Dielify (never a password used anywhere else),
  - they are stored encrypted with DPAPI in the "server_users" credential store,
  - the API is only reachable on the home network / Tailscale (see settings.server_bind).
Phase 5 adds per-device tokens for our own Android app on top of this.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
import threading
import time
from collections import defaultdict, deque
from dataclasses import dataclass

from . import credstore
from .paths import safe_name

STORE = "server_users"
MAX_FAILURES = 10          # failed logins per client address ...
FAILURE_WINDOW_S = 15 * 60  # ... within this window lock that address out for the window


@dataclass
class ServerUser:
    name: str
    profile: str
    password: str


def new_password() -> str:
    # ~95 bits; letters and digits only so it's easy to type into a phone.
    alphabet = "abcdefghijkmnpqrstuvwxyzACDEFGHJKLMNPQRTUVWXYZ2345679"
    return "-".join("".join(secrets.choice(alphabet) for _ in range(6)) for _ in range(3))


def _check_name(name: str) -> str:
    if not name or safe_name(name) != name or len(name) > 40:
        raise ValueError(f"'{name}' isn't a usable name (letters, numbers, - and _ only)")
    return name


def add_user(name: str, profile: str, password: str | None = None) -> ServerUser:
    _check_name(name)
    if credstore.load(name, STORE) is not None:
        raise ValueError(f"Server user '{name}' already exists")
    return set_password(name, profile, password)


def set_password(name: str, profile: str | None = None, password: str | None = None) -> ServerUser:
    existing = credstore.load(_check_name(name), STORE)
    profile = profile or (existing or {}).get("profile")
    if not profile:
        raise ValueError(f"No server user '{name}'")
    user = ServerUser(name, profile, password or new_password())
    credstore.save(name, {"profile": user.profile, "password": user.password}, STORE)
    return user


def get_user(name: str) -> ServerUser | None:
    try:
        data = credstore.load(safe_name(name), STORE) if name else None
    except credstore.CredentialError as e:
        import logging
        logging.getLogger(__name__).warning("Can't read the phone login file of %r: %s", name, e)
        return None
    if not data or safe_name(name) != name:
        return None
    return ServerUser(name, data["profile"], data["password"])


def list_users() -> list[ServerUser]:
    return [u for u in map(get_user, credstore.list_profiles(STORE)) if u]


def remove_user(name: str) -> bool:
    removed = credstore.delete(_check_name(name), STORE)
    revoke_all_tokens(name)  # a removed user's devices stop working too
    return removed


def check_subsonic(user: ServerUser, password: str | None, token: str | None,
                   salt: str | None) -> bool:
    """Subsonic login: either t=md5(password+s)&s=salt, or p=password / p=enc:HEX."""
    if token and salt:
        expected = hashlib.md5((user.password + salt).encode("utf-8")).hexdigest()
        return hmac.compare_digest(expected, token.lower())
    if password:
        if password.startswith("enc:"):
            try:
                password = bytes.fromhex(password[4:]).decode("utf-8")
            except ValueError:
                return False
        return hmac.compare_digest(password.encode("utf-8"), user.password.encode("utf-8"))
    return False


class Lockout:
    """Too many failed logins from one address -> refuse it for a while."""

    def __init__(self, max_failures: int = MAX_FAILURES, window_s: float = FAILURE_WINDOW_S):
        self.max_failures, self.window_s = max_failures, window_s
        self._failures: dict[str, deque[float]] = defaultdict(deque)
        self._lock = threading.Lock()

    def _trim(self, client: str, now: float) -> deque[float]:
        q = self._failures[client]
        while q and q[0] < now - self.window_s:
            q.popleft()
        return q

    def is_locked(self, client: str) -> bool:
        with self._lock:
            return len(self._trim(client, time.monotonic())) >= self.max_failures

    def failed(self, client: str) -> None:
        with self._lock:
            now = time.monotonic()
            self._trim(client, now).append(now)

    def succeeded(self, client: str) -> None:
        with self._lock:
            self._failures.pop(client, None)


# --- device tokens for our own /api (the Android app, test clients) -------------

TOKEN_PREFIX = "dielify_"


def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def create_token(user: ServerUser, device_name: str) -> tuple[int, str]:
    """A new random token for one device. Only its hash is stored; the caller shows
    the token to the device once."""
    from .library import connect
    token = TOKEN_PREFIX + secrets.token_urlsafe(32)
    with connect() as conn:
        token_id = conn.execute(
            "INSERT INTO device_tokens (username, device_name, token_hash, created_at) "
            "VALUES (?, ?, ?, ?)",
            (user.name, (device_name or "device")[:60], _token_hash(token), time.time())).lastrowid
    return token_id, token


def check_token(token: str) -> tuple[ServerUser, int] | None:
    from .library import connect
    if not token or not token.startswith(TOKEN_PREFIX):
        return None
    with connect() as conn:
        row = conn.execute("SELECT id, username FROM device_tokens WHERE token_hash = ?",
                           (_token_hash(token),)).fetchone()
        if row is None:
            return None
        conn.execute("UPDATE device_tokens SET last_used_at = ? WHERE id = ?", (time.time(), row["id"]))
    user = get_user(row["username"])
    return (user, row["id"]) if user else None


def list_tokens(username: str | None = None) -> list[dict]:
    from .library import connect
    with connect() as conn:
        sql = "SELECT id, username, device_name, created_at, last_used_at FROM device_tokens"
        rows = (conn.execute(sql + " WHERE username = ? ORDER BY id", (username,)) if username
                else conn.execute(sql + " ORDER BY id")).fetchall()
    return [dict(r) for r in rows]


def revoke_token(token_id: int, username: str | None = None) -> bool:
    """Revoke one device. With `username`, only that user's own devices."""
    from .library import connect
    with connect() as conn:
        sql, args = "DELETE FROM device_tokens WHERE id = ?", [token_id]
        if username:
            sql, args = sql + " AND username = ?", [token_id, username]
        return conn.execute(sql, args).rowcount > 0


def revoke_all_tokens(username: str) -> int:
    from .library import connect
    with connect() as conn:
        return conn.execute("DELETE FROM device_tokens WHERE username = ?", (username,)).rowcount


# --- cast links: speakers (Chromecast / Nest) play songs with these --------------------
# A speaker fetches the song itself, so the link must carry its own key. It never gets the
# phone's real login: a cast key only plays songs and shows covers, and stops working after
# CAST_TTL_S. Revoking the phone (or its person) ends its cast keys too.

CAST_PREFIX = "dielify_cast_"
CAST_TTL_S = 12 * 3600


def create_cast_token(user: ServerUser, device_id: int) -> tuple[str, float]:
    from .library import connect
    token = CAST_PREFIX + secrets.token_urlsafe(24)
    expires = time.time() + CAST_TTL_S
    with connect() as conn:
        conn.execute("DELETE FROM cast_tokens WHERE expires_at < ?", (time.time(),))
        conn.execute("INSERT INTO cast_tokens (token_hash, username, device_id, expires_at) VALUES (?,?,?,?)",
                     (_token_hash(token), user.name, device_id, expires))
    return token, expires


def check_cast_token(token: str) -> tuple[ServerUser, int] | None:
    """A valid cast key -> (user, device id), only while that phone is still signed in."""
    from .library import connect
    if not token or not token.startswith(CAST_PREFIX):
        return None
    with connect() as conn:
        row = conn.execute("SELECT c.username, c.device_id FROM cast_tokens c JOIN device_tokens d "
                           "ON d.id = c.device_id AND d.username = c.username "
                           "WHERE c.token_hash = ? AND c.expires_at > ?", (_token_hash(token), time.time())).fetchone()
    user = get_user(row["username"]) if row else None
    return (user, row["device_id"]) if user else None


# --- the desktop app's own key ------------------------------------------------------
# The desktop window gets a random key, made fresh each time the app starts and kept
# only in memory. It's handed to the window directly (never stored, never sent over
# the network to phones) and allows PC-only actions: music folder, profiles, YouTube
# sign-in, phone logins.

_desktop_token: str | None = None


def enable_desktop_token() -> str:
    global _desktop_token
    _desktop_token = "dielify_desktop_" + secrets.token_urlsafe(32)
    return _desktop_token


def is_desktop_token(token: str | None) -> bool:
    return bool(token and _desktop_token and hmac.compare_digest(token, _desktop_token))
